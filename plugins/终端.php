<?php
// ============================================================
// 终端执行插件：群里发「终端 / 执行」前缀执行服务器 shell 命令
// ------------------------------------------------------------
// 命令：
//   终端 <命令>          → 在服务器执行命令并回传完整输出
//   执行 <命令>          → 同「终端」
// 示例：
//   终端 ls -la
//   终端 cd /var/www/php && pm2 status
//   终端 pm2 logs qqbot --lines 50 --nostream
// ------------------------------------------------------------
// 权限：仅 超级主人 / 群主 / 群管理员（后台成员管理标注 role）可用。
// 输出：只回复发起命令的群；超长自动截取重点错误 + 末尾 30 行。
// 安全：命令由 php 执行，不设白名单（任意命令能力），因此必须以群角色授权为前提；
//       建议仅在信任的机器人所在群使用。
// ============================================================

$in = json_decode(stream_get_contents(STDIN), true);
if (!$in || !is_array($in)) { fwrite(STDERR, "无效输入\n"); exit(0); }

$类型 = (string)($in['type'] ?? '');
$消息 = trim((string)($in['content'] ?? ''));

// 剥离消息开头对机器人的 @ 提及（与更新系统一致），只保留命令本体
while (true) {
  $去 = preg_replace('/^<@!?[0-9A-Fa-f]+>\s*/', '', $消息);
  $去 = preg_replace('/^@\S+\s*/', '', $去);
  if ($去 === $消息) break;
  $消息 = trim($去);
}

$群 = (string)($in['groupId'] ?? '');
$用户 = (string)($in['userId'] ?? '');

if ($类型 !== 'group') exit(0); // 仅群聊
if ($群 === '') exit(0);

// 触发词：终端 / 执行（后跟命令）；单独发「终端」或「执行」给用法提示
$命中 = false;
$命令 = '';
if ($消息 === '终端' || $消息 === '执行') {
  $at = "<@!" . $用户 . ">";
  文字($at . "\n📟 终端执行：发送「终端 <命令>」或「执行 <命令>」在服务器上执行 shell 命令，\n例如：\n终端 ls -la\n终端 cd /var/www/php && pm2 status\n终端 pm2 logs qqbot --lines 30 --nostream\n\n⚠️ 仅 超级主人 / 群主 / 群管理员 可用，输出只回本群。");
  exit(0);
}
if (preg_match('/^(?:终端|执行)\s+([\s\S]+)$/u', $消息, $mm)) {
  $命令 = trim($mm[1]);
  if ($命令 !== '') $命中 = true;
}
if (!$命中) exit(0); // 不是本插件的命令

$at = "<@!" . $用户 . ">";

// ========== 权限：超主 / 群主 / 群管理 ==========
if (!终端授权($群, $用户)) {
  文字($at . "\n🔒 终端命令仅 超级主人 / 群主 / 群管理员 可使用。\n如需维护，请联系管理员或群主。");
  exit(0);
}

// 执行前先给个「开始执行」提示（exec 可能耗时，避免像"没回应"）
文字($at . "\n⌨️ 正在执行：\n" . $命令);

$r = 执行终端命令($命令, 55);
$code = (int)$r['code'];

// 完整输出优先，超长截断（重点错误 + 末尾 30 行）；分多条发送避免单条超限
$pieces = array();
$out = 截断终端输出($r['lines'], 3000, 30);
$tailNote = $out['truncated'] ? "\n…（已截断）" : '';
$pieces[] = '```' . $out['text'] . '```' . $tailNote;
$pieces[] = $code === 0 ? '✅ 执行完成（退出码 0）' : '❌ 执行结束，退出码 ' . $code;
foreach ($pieces as $p) 文字($at . "\n" . $p);
exit(0);
